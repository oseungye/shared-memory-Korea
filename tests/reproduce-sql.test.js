/* 재현용 SQL — 실행: npm test
   · supabase/reproduce/00-base-shared_expressions.sql 이 새 프로젝트 전용이며(운영 DB에서는 바로 멈춤),
     운영 DB와 같은 기본 컬럼을 만들고, 지우거나 바꾸는 문장이 없는지 확인합니다.
   · 실제 적용 검증(빈 PostgreSQL 16에 0–11번 순서 적용)은 supabase/reproduce/README.md 기록 참고. */
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const DIR = path.join(__dirname, '..', 'supabase');
const BASE = fs.readFileSync(path.join(DIR, 'reproduce', '00-base-shared_expressions.sql'), 'utf8');
const CODE = BASE.replace(/--.*$/gm, '');
const GUIDE = fs.readFileSync(path.join(DIR, 'reproduce', 'README.md'), 'utf8');

test('안전장치가 맨 앞: 테이블이 이미 있으면(운영 DB) 아무것도 하지 않고 멈춘다', () => {
  const guard = CODE.indexOf("to_regclass('public.shared_expressions') is not null");
  assert.ok(guard > 0);
  assert.ok(guard < CODE.indexOf('create table'), '안전장치가 테이블 생성보다 먼저');
  assert.match(CODE, /raise exception/);
});

test('운영 DB와 같은 기본 컬럼·기본값을 만들고, 지우거나 바꾸는 문장이 없다', () => {
  ['id           bigint generated by default as identity primary key', "author_name  text not null default '익명'",
    "country_code text not null default 'ETC'", 'content      text not null', 'created_at   timestamptz not null default now()', 'reason       text']
    .forEach(col => assert.ok(CODE.includes(col), col));
  assert.match(CODE, /alter table public\.shared_expressions enable row level security;/);
  assert.doesNotMatch(CODE, /\b(drop|delete|truncate|update)\b/i);
});

test('적용 순서 안내의 파일이 모두 저장소에 있다', () => {
  const files = [...GUIDE.matchAll(/`(supabase\/[^`]+\.sql)`/g)].map(m => m[1]);
  assert.ok(files.length >= 12, String(files.length));
  files.forEach(f => assert.ok(fs.existsSync(path.join(__dirname, '..', f)), f));
});

-- · 운영 DB에서는 이 테이블을 프로젝트 초기에 Supabase 대시보드로 만들었고, 저장소 SQL에는 CREATE 문이 없었습니다.
-- · 새 Supabase 프로젝트에서 DB를 처음부터 만들 때, source/supabase/ 의 SQL보다 먼저 이 파일을 실행하세요.
-- · 컬럼·기본값·NULL 여부는 운영 DB의 information_schema에서 읽은 값과 같습니다. 이후 컬럼은 다음 SQL들이 추가합니다.
-- · **운영 DB에는 실행하지 마세요.** 실수로 실행해도 아래 안전장치가 테이블이 이미 있는 것을 보고
--   아무것도 바꾸지 않고 즉시 멈춥니다(오류 메시지로 끝남).

-- 안전장치: 이미 shared_expressions 가 있는 DB(운영 DB 포함)에서는 아무것도 하지 않고 멈춤
do $$ begin
  if to_regclass('public.shared_expressions') is not null then
    raise exception 'shared_expressions 테이블이 이미 있습니다 — 새 프로젝트 전용 파일이므로 실행을 멈춥니다(바뀐 것 없음).';
  end if;
end $$;

create table if not exists public.shared_expressions (
  id           bigint generated by default as identity primary key,
  event_key    text not null,
  author_name  text not null default '익명',
  country_code text not null default 'ETC',
  content      text not null,
  created_at   timestamptz not null default now(),
  reason       text
);

alter table public.shared_expressions enable row level security;

-- 초기 공개 정책: 누구나 조회·등록 (수정·삭제 정책 없음).
-- 이후 2026-10-prefinal-hardening.sql 이 권한을 컬럼 단위로 좁히고,
-- 2026-10-server-moderation.sql 이 조회 조건을 (not is_hidden) 으로 바꿉니다.
do $$ begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'shared_expressions' and policyname = '공동 표현 조회 허용') then
    create policy "공동 표현 조회 허용" on public.shared_expressions for select to anon, authenticated using (true);
  end if;
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'shared_expressions' and policyname = '공동 표현 등록 허용') then
    create policy "공동 표현 등록 허용" on public.shared_expressions for insert to anon, authenticated with check (true);
  end if;
end $$;

-- · Edge Function `ask-ai`(supabase/functions/ask-ai)가 **서비스 롤**로만 읽고 씁니다.
--   사이트(anon)는 이 테이블을 읽거나 쓸 수 없고, 사이트 코드는 이 테이블을 직접 다루지 않습니다.
-- · 저장하는 것: 호출 시각과 IP 해시(secret ASK_AI_IP_SALT로 솔트한 SHA-256 — 솔트 설정 권장). IP 원문·학생 답·AI 응답은 저장하지 않습니다.
-- · 한도(함수 코드): IP당 시간당 300회, 전체 하루 1,000회. 넘으면 429 → 사이트는 미리 써 둔 질문으로 이어갑니다.
-- · 이 SQL을 실행하기 전에는 함수가 503을 돌려주고, 사이트는 폴백으로 끝까지 동작합니다(열어 두지 않음).

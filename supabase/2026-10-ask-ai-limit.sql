-- 1) 호출 기록 테이블 ---------------------------------------------
create table if not exists public.ask_ai_calls (
  id        bigint generated by default as identity primary key,
  ip_hash   text not null check (ip_hash ~ '^[0-9a-f]{64}$'),
  called_at timestamptz not null default now()
);

comment on table public.ask_ai_calls is
  '질문하는 AI(Edge Function ask-ai) 호출 한도 기록. 시각과 IP 해시(솔트 권장)만 저장 — IP 원문·학생 답·AI 응답 없음. 서비스 롤 전용';

create index if not exists ask_ai_calls_called_at_idx on public.ask_ai_calls (called_at);
create index if not exists ask_ai_calls_ip_hash_idx  on public.ask_ai_calls (ip_hash, called_at);

-- 2) anon·authenticated 권한 전부 회수 (정책도 만들지 않음 → RLS가 켜져 있어도 접근 경로 없음) ------------------
alter table public.ask_ai_calls enable row level security;
revoke all on table public.ask_ai_calls from public, anon, authenticated;

-- 3) 7일 지난 행 정리 (함수가 호출 50회에 한 번쯤 부릅니다. pg_cron이 있으면 하루 한 번 걸어도 됩니다) ----------
create or replace function public.ask_ai_calls_cleanup()
returns void
language sql
set search_path = ''
as $$
  delete from public.ask_ai_calls where called_at < now() - interval '7 days';
$$;

revoke all on function public.ask_ai_calls_cleanup() from public, anon, authenticated;


-- 1) 객관식 답에 묶음 번호 칸 추가 ---------------------------------
alter table public.exploration_choices add column if not exists submission_id uuid;
grant insert (submission_id) on table public.exploration_choices to anon, authenticated;
create index if not exists exploration_choices_submission_idx on public.exploration_choices (submission_id);

-- 2) 한 줄 소감 테이블 (비공개) ------------------------------------
create table if not exists public.exploration_reflections (
  id            bigint generated by default as identity primary key,
  event_key     text not null check (event_key ~ '^[a-z0-9_]{1,40}$'),
  submission_id uuid not null,
  content       text not null check (char_length(btrim(content)) between 1 and 300),
  created_at    timestamptz not null default now()
);

comment on table public.exploration_reflections is
  '기본 체험 한 줄 소감 (이름 없이 저장, 다른 참여자에게 비공개). submission_id 로 같은 카드의 객관식 답과 묶임';

create index if not exists exploration_reflections_event_idx on public.exploration_reflections (event_key, created_at);
create index if not exists exploration_reflections_submission_idx on public.exploration_reflections (submission_id);

alter table public.exploration_reflections enable row level security;

-- anon 은 세 칸만 등록할 수 있습니다 (id·created_at은 서버가 정함). 조회 정책은 만들지 않습니다.
revoke all on table public.exploration_reflections from anon, authenticated;
grant insert (event_key, submission_id, content) on table public.exploration_reflections to anon, authenticated;

drop policy if exists "한 줄 소감 등록 허용" on public.exploration_reflections;
create policy "한 줄 소감 등록 허용" on public.exploration_reflections
  for insert to anon, authenticated
  with check (true);

-- 3) 자동 도배 방지 (객관식 응답과 같은 방식) ------------------------
create or replace function public.sm_reflection_insert_guard()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if (select count(*) from public.exploration_reflections r
      where r.created_at > now() - interval '1 minute') >= 300 then
    raise exception 'sm_rate_limited' using errcode = 'P0001', hint = '소감이 몰려 잠시 멈췄습니다.';
  end if;
  return new;
end;
$$;

revoke all on function public.sm_reflection_insert_guard() from public, anon, authenticated;

create or replace trigger exploration_reflections_insert_guard
  before insert on public.exploration_reflections
  for each row execute function public.sm_reflection_insert_guard();


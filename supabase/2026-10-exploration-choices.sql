-- 무엇을 저장하나요
--   · 기본 체험(임진왜란·재일조선인)에서 학생이 고른 객관식 선택지 id만 저장합니다.
--     예) ('imjin', 'name_focus', 'many_names')
--   · 학생이 "내 선택을 익명 통계에 보태기"에 동의했을 때만 사이트가 보냅니다.
--   · 닉네임·문장·한 줄 소감·연령대·참여자 키·IP를 이 테이블에 넣지 않습니다(행끼리 이어 붙일 수 없음).
--   · 주관식 공동 표현(shared_expressions)과 완전히 다른 테이블입니다 → 두 데이터를 섞지 않고 따로 분석합니다.
--
-- 누가 무엇을 볼 수 있나요
--   · anon 은 등록(insert)만 할 수 있고, 행을 직접 조회할 수 없습니다.
--   · 공개되는 것은 집계 함수 choice_counts(사건)의 '선택지별 수'뿐이며,
--     한 질문의 응답이 sm_min_group_size()(기본 5) 미만이면 수를 돌려주지 않습니다.
-- ============================================================

-- 1) 응답 테이블 ------------------------------------------------
create table if not exists public.exploration_choices (
  id          bigint generated by default as identity primary key,
  event_key   text not null check (event_key in ('imjin', 'zainichi')),
  question_id text not null check (question_id ~ '^[a-z0-9_]{1,40}$'),
  option_id   text not null check (option_id ~ '^[a-z0-9_]{1,40}$'),
  created_at  timestamptz not null default now()
);

comment on table public.exploration_choices is
  '기본 체험 객관식 응답(동의한 경우만). 정답이 없는 관점 선택이며 개인을 식별할 값은 저장하지 않음';

create index if not exists exploration_choices_event_idx
  on public.exploration_choices (event_key, question_id, option_id);

alter table public.exploration_choices enable row level security;

-- anon 은 event_key·question_id·option_id 세 칸만 등록할 수 있습니다 (id·created_at은 서버가 정함).
revoke all on table public.exploration_choices from anon, authenticated;
grant insert (event_key, question_id, option_id) on table public.exploration_choices to anon, authenticated;

drop policy if exists "객관식 응답 등록 허용" on public.exploration_choices;
create policy "객관식 응답 등록 허용" on public.exploration_choices
  for insert to anon, authenticated
  with check (true);
-- 조회(select) 정책은 만들지 않습니다 → 행 단위로는 아무도(anon) 읽을 수 없습니다.

-- 2) 자동 도배 방지 (기존 공동 표현의 빈도 제한과 같은 방식) ------
create or replace function public.sm_choice_insert_guard()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if (select count(*) from public.exploration_choices c
      where c.created_at > now() - interval '1 minute') >= 600 then
    raise exception 'sm_rate_limited' using errcode = 'P0001', hint = '응답이 몰려 잠시 멈췄습니다.';
  end if;
  return new;
end;
$$;

revoke all on function public.sm_choice_insert_guard() from public, anon, authenticated;

create or replace trigger exploration_choices_insert_guard
  before insert on public.exploration_choices
  for each row execute function public.sm_choice_insert_guard();

-- 3) 집계 함수 — 선택지별 수만 공개 (작은 표본은 숨김) -------------
create or replace function public.choice_counts(p_event_key text)
returns table (question_id text, option_id text, n bigint)
language sql
stable
security definer
set search_path = ''
as $$
  with totals as (
    select c.question_id, count(*) as total
    from public.exploration_choices c
    where c.event_key = p_event_key
    group by c.question_id
  )
  select c.question_id, c.option_id, count(*)::bigint as n
  from public.exploration_choices c
  join totals t on t.question_id = c.question_id
  where c.event_key = p_event_key
    and t.total >= public.sm_min_group_size()
  group by c.question_id, c.option_id;
$$;

revoke all on function public.choice_counts(text) from public, anon, authenticated;
grant execute on function public.choice_counts(text) to anon;


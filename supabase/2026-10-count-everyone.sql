-- 1) 참여 기록 (2026-10-participation-pings.sql 과 같음) ---------------
create table if not exists public.participation_pings (
  id              bigint generated by default as identity primary key,
  event_key       text not null check (event_key ~ '^[a-z0-9_]{1,40}$'),
  participant_key text not null check (char_length(participant_key) between 8 and 64),
  created_at      timestamptz not null default now(),
  unique (participant_key, event_key)
);

comment on table public.participation_pings is
  '참여자 수 집계용 참여 기록. 사건 이름과 브라우저 무작위 키만 저장 (답·문장·개인정보 없음)';

alter table public.participation_pings enable row level security;

revoke all on table public.participation_pings from anon, authenticated;
grant insert (event_key, participant_key) on table public.participation_pings to anon, authenticated;

drop policy if exists "참여 기록 등록 허용" on public.participation_pings;
create policy "참여 기록 등록 허용" on public.participation_pings
  for insert to anon, authenticated
  with check (true);

create or replace function public.sm_ping_insert_guard()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if (select count(*) from public.participation_pings g
      where g.created_at > now() - interval '1 minute') >= 600 then
    raise exception 'sm_rate_limited' using errcode = 'P0001', hint = '참여가 몰려 잠시 멈췄습니다.';
  end if;
  return new;
end;
$$;

revoke all on function public.sm_ping_insert_guard() from public, anon, authenticated;

create or replace trigger participation_pings_insert_guard
  before insert on public.participation_pings
  for each row execute function public.sm_ping_insert_guard();

-- 2) 이전 참여자 추정치 (운영자만 · 사이트에서 읽거나 쓸 수 없음) ---------
create table if not exists public.participation_baseline (
  source        text primary key check (source ~ '^[a-z0-9_]{1,60}$'),
  participants  integer not null check (participants >= 0),
  counted_until timestamptz not null,
  note          text not null
);

comment on table public.participation_baseline is
  '참여 기록(participation_pings) 이전, 서버에 행이 남지 않은 참여자의 추정치. 숫자만 저장';

alter table public.participation_baseline enable row level security;
revoke all on table public.participation_baseline from anon, authenticated;
-- 정책·권한을 만들지 않습니다 → anon·authenticated 는 읽기·쓰기 모두 불가 (집계 함수 안에서만 사용)

insert into public.participation_baseline (source, participants, counted_until, note)
values ('quick_card_screens_logs', 52, '2026-10-23 13:25:00+00',
        '기본 체험 카드 화면을 연 기기(IP+브라우저) 57대 중 객관식·공동 표현 전송 기기 5대 제외. API 요청 로그 기준 추정')
on conflict (source) do nothing;

-- 3) 참여자 수 집계 ----------------------------------------------
create or replace function public.participation_summary()
returns table(participants bigint, completed_participants bigint, expressions bigint)
language sql
stable security definer
set search_path = ''
as $$
  select
    (select count(*) from (
        select p.participant_key
          from public.expression_participants p
          join public.shared_expressions s on s.id = p.expression_id
         where not s.is_hidden
        union
        select g.participant_key from public.participation_pings g
      ) as keyed)
      + (select count(*) from public.shared_expressions s
         where not s.is_hidden
           and not exists (select 1 from public.expression_participants p where p.expression_id = s.id))
      + (select count(*) from (select distinct c.event_key, c.created_at
                                 from public.exploration_choices c
                                where c.created_at < coalesce((select min(g.created_at) from public.participation_pings g), 'infinity'::timestamptz)
                              ) as choice_submissions_before_pings)
      + (select coalesce(sum(b.participants), 0) from public.participation_baseline b),
    (select count(distinct p.participant_key)
       from public.expression_participants p
       join public.shared_expressions s on s.id = p.expression_id
      where s.completed_flow is true and not s.is_hidden),
    (select count(*) from public.shared_expressions s where not s.is_hidden);
$$;

revoke all on function public.participation_summary() from public, anon, authenticated;
grant execute on function public.participation_summary() to anon;

